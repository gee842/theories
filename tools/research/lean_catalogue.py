def discover(glob: str) -> list[str]:
    command = ["rg", "--files", "--hidden", "--no-ignore", "-0", "-g", glob]
    for directory in EXCLUDED:
        command += ["-g", f"!**/{directory}/**"]
    result = subprocess.run(command, cwd=ROOT, check=True, capture_output=True)
    return sorted(x.decode("utf-8") for x in result.stdout.split(b"\0") if x)


SCRUB_NEXT = {"code": re.compile(r'/-|--|"'), "comment": re.compile(r"/-|-/"), "string": re.compile(r'\\|"')}


def scrub(source: str) -> str:
    """Blank nested comments and strings while retaining offsets and line breaks."""
    out = []
    i = 0
    depth = 0
    string = False
    n = len(source)

    def blank(j: int, k: int) -> None:
        out.append(re.sub(r"[^\n]", " ", source[j:k]))

    while i < n:
        mode = "comment" if depth else "string" if string else "code"
        match = SCRUB_NEXT[mode].search(source, i)
        stop = match.start() if match else n
        if mode == "code":
            out.append(source[i:stop])
        else:
            blank(i, stop)
        if not match:
            break
        token = match.group()
        if mode == "comment":
            depth += 1 if token == "/-" else -1
            blank(stop, stop + 2)
            i = stop + 2
        elif mode == "string":
            if token == '"':
                string = False
                blank(stop, stop + 1)
                i = stop + 1
            else:
                blank(stop, min(stop + 2, n))
                i = stop + 2
        elif token == "/-":
            depth = 1
            blank(stop, stop + 2)
            i = stop + 2
        elif token == "--":
            end = source.find("\n", stop)
            end = n if end == -1 else end
            blank(stop, end)
            i = end
        else:
            string = True
            blank(stop, stop + 1)
            i = stop + 1
    return "".join(out)


def parse_lean(raw: bytes) -> dict:
    source = raw.decode("utf-8")
    clean = scrub(source)
    declarations = []
    imports = []
    scopes = []
    for number, line in enumerate(clean.splitlines(), 1):
        if match := re.match(r"^\s*import\s+(.+)$", line):
            imports.extend(match.group(1).split())
        if match := re.match(r"^\s*(namespace|section|mutual)\b\s*(\S*)", line):
            scopes.append((match.group(1), match.group(2)))
        elif match := re.match(r"^\s*end(?:\s+(\S+))?\s*$", line):
            if scopes:
                scopes.pop()
        if match := DECL.match(line):
            name = match.group("name")
            namespace = ".".join(s[1] for s in scopes if s[0] == "namespace")
            qualified = name[len("_root_."):] if name.startswith("_root_.") else ".".join(filter(None, (namespace, name)))
            declarations.append({"kind": match.group("kind"), "name": name, "qualified_name_hint": qualified, "line": number})
    return {
        "byte_size": len(raw),
        "line_count": len(source.splitlines()),
        "imports": imports,
        "declarations": declarations,
        "declaration_counts": dict(sorted(Counter(d["kind"] for d in declarations).items())),
        "textual_markers": {
            token: [clean.count("\n", 0, m.start()) + 1 for m in re.finditer(r"\b" + token + r"\b", clean)]
            for token in ("sorry", "admit", "axiom", "native_decide", "unsafe")
        },
        "print_axioms_commands": len(re.findall(r"#print\s+axioms\b", clean)),
    }


def role(path: str, content: dict) -> str:
    return path_role(path) or ("audit-driver" if not content["declarations"] and content["print_axioms_commands"] else "working-source")


def path_role(path: str) -> str | None:
    """The role a path alone decides, or None where the file's content decides."""
    parts = Path(path).parts
    if parts[0] == "sources":
        return "imported-archive"
    if parts[0] == "drafts":
        return "historical-draft"
    # This package's README and evidence/manifest.json identify a frozen parent
    # semantic-source capture. Its omitted #print commands change the bytes,
    # but do not make it another working proof module. Keep the exception narrow:
    # an arbitrary directory named "evidence" is not necessarily a snapshot.
    if path.endswith("/reason-consumer/transport/evidence/RecipientReasons.lean"):
        return "saved-copy"
    if any(p == "development" or (p.endswith("-development") and p != "valuation-development") or p.startswith("attempt-") or p in ("review-history", "review-probe-authority") for p in parts[:-1]) or parts[0] == "_process":
        return "development-attempt"
    if any(
        p in ("sources", "runs", "snapshots", "source-snapshots", "verification", "verification-history", "isolated", "build", "nondual-independent-logs", "legacy-replays")
        or p.endswith(("-runs", "-verification", "-checks"))
        or re.fullmatch(r"\d{10,}|\d{8}T\d{6}.*Z", p)
        for p in parts[:-1]
    ):
        return "saved-copy"
    return None


