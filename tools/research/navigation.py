def validate_history():
    errors = []
    for original, item in read(HISTORY)['documents'].items():
        for version in [item] + item.get('prior_versions', []):
            for key, hashkey in [('raw', 'sha256'), ('reading', 'reading_sha256')]:
                p = ROOT / version[key]
                if not p.exists() or sha(p.read_bytes()) != version[hashkey]:
                    errors.append('changed preservation artifact: ' + str(p))
    return errors


def preserve_view(path, note):
    """Explicitly acknowledge reviewed prose without changing scientific records."""
    history = read(HISTORY)
    previous = read(MANIFEST) if MANIFEST.exists() else {'schema_version': 1, 'files': {}}
    if path not in history['documents'] and path not in previous['files']:
        raise ValueError('Not a managed overview: ' + path)
    saved = preserve(path)
    old = history['documents'].get(path)
    if old and old['sha256'] != saved['sha256']:
        saved['prior_versions'] = old.get('prior_versions', []) + [{k: v for k, v in old.items() if k != 'prior_versions'}]
    elif old:
        saved = old
    history['documents'][path] = saved
    history.setdefault('reconciliations', []).append({'path': path, 'sha256': saved['sha256'], 'note': note})
    HISTORY.write_text(json.dumps(history, ensure_ascii=False, indent=2) + '\n')
    if MANIFEST.exists():
        previous['files'][path] = saved['sha256']
        MANIFEST.write_text(json.dumps(previous, indent=2) + '\n')
    return saved


def write_views(outputs, initial_generated=None):
    """Check every old version before writing; leave concurrent additions untouched."""
    history = read(HISTORY)['documents']
    previous = read(MANIFEST) if MANIFEST.exists() else {'files': {}}
    observed, errors = {}, []
    for path in outputs:
        p = ROOT / path
        raw = p.read_bytes() if p.exists() else None
        observed[path] = raw
        expected = previous['files'].get(path, history.get(path, {}).get('sha256', (initial_generated or {}).get(path)))
        if raw is not None and sha(raw) != expected and raw.decode() != outputs[path]:
            errors.append('Unincorporated concurrent edit; preserve and reconcile before rendering: ' + path)
    if errors:
        return errors
    for path, body in outputs.items():
        p = ROOT / path
        if (p.read_bytes() if p.exists() else None) != observed[path]:
            return ['Concurrent edit during rendering: ' + path]
        p.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.NamedTemporaryFile(dir=p.parent, delete=False) as stream:
            stream.write(body.encode())
            temporary = stream.name
        os.replace(temporary, p)
    previous['files'].update({p: sha(s.encode()) for p, s in outputs.items()})
    MANIFEST.write_text(json.dumps({'schema_version': 1, 'files': previous['files']}, indent=2) + '\n')
    return []
