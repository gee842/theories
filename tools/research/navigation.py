def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def read(path):
    return json.loads(path.read_text())


def link(path, base, label):
    file, sep, fragment = path.partition('#')
    return f'[{label}]({os.path.relpath(ROOT / file, (ROOT / base).parent)}{sep}{fragment})'


def adapt_links(body, original, destination):
    def adapt(target):
        angle = target.startswith('<') and target.endswith('>')
        target = target.strip('<>')
        parsed = urlsplit(target)
        if parsed.scheme or target.startswith('/') or not parsed.path:
            return '<' + target + '>' if angle else target
        resolved = ((ROOT / original).parent / unquote(parsed.path)).resolve()
        relative = os.path.relpath(resolved, (ROOT / destination).parent)
        suffix = ('?' + parsed.query if parsed.query else '') + ('#' + parsed.fragment if parsed.fragment else '')
        return '<' + relative + suffix + '>' if angle or ' ' in relative else relative + suffix
    body = re.sub(r'(\]\()(<[^>\n]+>|[^\s)]+)(\))', lambda m: m[1] + adapt(m[2]) + m[3], body)
    body = re.sub(r'^(\[[^\]\n]+\]:\s*)(\S+)', lambda m: m[1] + adapt(m[2]), body, flags=re.M)
    body = re.sub(r'(href=["\'])([^"\']+)(["\'])', lambda m: m[1] + adapt(m[2]) + m[3], body)
    return body


def preserve(original):
    """Keep exact bytes plus a separately labelled, link-adapted reading edition."""
    p = ROOT / original
    raw = p.read_bytes()
    digest = sha(raw)
    directory = ROOT / '_process/architecture/history' / digest[:16]
    directory.mkdir(parents=True, exist_ok=True)
    raw_path = directory / p.name
    portable = directory / (p.stem + '.reading.md')
    for dest, content in [(raw_path, raw), (portable, ('> Historical reading edition; local links adapted from `' + original + '`. The adjacent original retains exact bytes.\n\n' + adapt_links(raw.decode(), original, str(portable.relative_to(ROOT)))).encode())]:
        if dest.exists() and dest.read_bytes() != content:
            raise ValueError('Refusing to overwrite preservation artifact: ' + str(dest))
        dest.write_bytes(content)
    return {'original': original, 'sha256': digest, 'raw': str(raw_path.relative_to(ROOT)), 'reading': str(portable.relative_to(ROOT)), 'reading_sha256': sha(portable.read_bytes())}


def goals():
    directory = read(CONFIG)['goal_directory']
    return [read(p) for p in sorted((ROOT / directory).glob('*.json'))]


def featured_results(records, config=None):
    """Resolve explicit editorial order without promoting open or retired claims."""
    configured = (read(CONFIG) if config is None else config).get('readme_featured_results', [])
    if not isinstance(configured, list) or not all(isinstance(ident, str) for ident in configured):
        raise ValueError('readme_featured_results must be a list of result IDs')
    if len(configured) != len(set(configured)):
        raise ValueError('readme_featured_results contains duplicate result IDs')
    by_id = {r['id']: r for r in records}
    selected = []
    for ident in configured:
        if ident not in by_id:
            raise ValueError('readme_featured_results refers to missing result: ' + ident)
        record = by_id[ident]
        if record.get('status') not in {'recorded-checked', 'reviewed-scoped'} or record.get('kind') == 'target':
            raise ValueError('readme_featured_results requires a completed scoped result: ' + ident)
        if not registry.valid_overview(record.get('overview')):
            raise ValueError('readme_featured_results requires bilingual overview title, summary and evidence: ' + ident)
        selected.append(record)
    return selected


def valid_goal_overview(value):
    return isinstance(value, dict) and all(registry.pair(value.get(key)) for key in ('title', 'summary', 'next_step'))


def research_goals(goal_records, config=None):
    """Select scoped research directions; scientific status stays in result records."""
    configured = (read(CONFIG) if config is None else config).get('readme_research_goals', [])
    if not isinstance(configured, list) or not all(isinstance(ident, str) for ident in configured):
        raise ValueError('readme_research_goals must be a list of goal IDs')
    if len(configured) != len(set(configured)):
        raise ValueError('readme_research_goals contains duplicate goal IDs')
    by_id = {g['id']: g for g in goal_records}
    selected = []
    for ident in configured:
        if ident not in by_id:
            raise ValueError('readme_research_goals refers to missing goal: ' + ident)
        goal = by_id[ident]
        if not valid_goal_overview(goal.get('overview')):
            raise ValueError('readme_research_goals requires bilingual overview title, summary and next_step: ' + ident)
        selected.append(goal)
    return selected


def validate_goals(records):
    ids = {r['id'] for r in records}
    goal_records = goals()
    seen, errors = set(), []
    for g in goal_records:
        ident = g.get('id')
        if ident in seen or not re.fullmatch(r'[a-z][a-z0-9-]+', ident or ''):
            errors.append('invalid or duplicate goal id: ' + str(ident))
        seen.add(ident)
        for field in ('title', 'scope', 'objective', 'completion', 'premises'):
            if not registry.pair(g.get(field)):
                errors.append(f'{ident}: bilingual {field} required')
        if 'overview' in g and not valid_goal_overview(g['overview']):
            errors.append(f'{ident}: overview requires bilingual title, summary and next_step')
        if g.get('scope_type') not in {'project-direction', 'authorized-session', 'completed-route'}:
            errors.append(f'{ident}: scope_type required')
        if not g.get('sources'):
            errors.append(f'{ident}: authorization sources required')
        for path in g.get('sources', []):
            if registry.path_in_repo(path.split('#')[0]) is None:
                errors.append(f'{ident}: missing authorization {path}')
        for ident in g.get('result_ids', []):
            if ident not in ids:
                errors.append('goal refers to missing result: ' + ident)
    try:
        featured_results(records)
    except ValueError as exc:
        errors.append(str(exc))
    try:
        research_goals(goal_records)
    except ValueError as exc:
        errors.append(str(exc))
    return errors


def preserved_anchors(original, history):
    # Preserve every old heading/explicit anchor at the old URL as a history link.
    from tools.research.reading_catalogue import anchors
    saved = history['documents'][original]
    targets = {}
    for version in saved.get('prior_versions', []) + [saved]:
        targets.update({a: version['reading'] for a in anchors(ROOT / version['reading'])})
    lines = ['', '<details>', '<summary>Historical section links / 历史章节链接</summary>', '']
    for anchor in sorted(targets):
        safe = anchor.replace('"', '&quot;')
        lines += [f'<a id="{safe}"></a>', link(targets[anchor] + '#' + anchor, original, 'Historical section / 历史章节: ' + anchor), '']
    return lines + ['</details>', '']


def table(records, base, open_only=False):
    lines = ['| Result / 成果 | Recorded scope / 已登记范围 | Source / 来源 |', '|---|---|---|']
    for r in records:
        if open_only and r['kind'] != 'target':
            continue
        page = str(registry.record_path(r).with_suffix('.md').relative_to(ROOT))
        lines += ['| ' + link(page, base, registry.bilingual(r['title'])) + ' | ' + r['status'] + ' | ' + link(r['canonical_source'], base, Path(r['canonical_source']).name) + ' |']
    return lines


