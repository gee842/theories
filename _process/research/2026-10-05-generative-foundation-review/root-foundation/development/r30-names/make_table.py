#!/usr/bin/env python3
"""R30: write RENAME-TABLE.json, the final table, from rename-draft.json (the generated draft with its decisions).

usage: python3 -B make_table.py [BASE_RECEIPT NEW_RECEIPT]

`renamed` lists every applied row (old, new, kind, reason); `not_renamed` the rows judged and left, with the
decision; `declarations`, `modules`, `paths` and `namespaces` are the lookups other tools read (the RO build
reads `declarations`). With the two receipts, the declarations are also read off them: the names in the base
receipt and not in the new one must be exactly the renamed ones, and the new names exactly the added ones."""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
t = json.load(open(HERE / 'rename-draft.json'))
LEANDIR = 'experiments/integrated-correction/general-framework/generative-basis/lean/becoming/'
ren, nren = [], []
for r in t:
    row = {'old': r['old_full_name'], 'new': r['new_full_name'], 'kind': r['kind'], 'reason': r['reason']}
    if r['decision'].startswith('apply'):
        if r['decision'] != 'apply (confidence high)':
            row['decision'] = r['decision']
        if r.get('draft_new_name'):
            row['draft_new_name'] = r['draft_new_name']
            row['note'] = r.get('note', '')
        ren.append(row)
    else:
        row['decision'] = r['decision']
        nren.append(row)
decl = {r['old']: r['new'] for r in ren if r['kind'] == 'decl'}
mods = {r['old']: r['new'] for r in ren if r['kind'] == 'module'}
nss = {r['old']: r['new'] for r in ren if r['kind'] == 'namespace'}
out = {
    'about': ('R30, board item of the twentieth review (one notion, one name), 20 October 2026: the declarations, '
              'namespaces and modules renamed, statements unchanged; no aliases (the pure core has no `alias`, and '
              'a copy would count as a theorem), so this table is the lookup for every old name. Generated by '
              'gen.py on R29\'s head, decided by decide.py, applied by apply.py, positive.py and manual.py.'),
    'renamed': ren,
    'not_renamed': nren,
    'declarations': decl,
    'modules': mods,
    'paths': {LEANDIR + 'Becoming/' + o[9:] + '.lean': LEANDIR + 'Becoming/' + n[9:] + '.lean' for o, n in mods.items()},
    'namespaces': nss,
    'binder': {'positive': 'relevance'},
}
if len(sys.argv) > 2:
    def names(p):
        r = json.load(open(p))
        return {d['name'] for m in r['modules'] if m.get('layer') == 'core' for d in m['declarations']}
    a, b = names(sys.argv[1]), names(sys.argv[2])
    gone, new = a - b, b - a
    assert gone == set(decl), ('removed but not in the table', sorted(gone - set(decl))[:20],
                               'in the table but not removed', sorted(set(decl) - gone)[:20])
    assert new == set(decl.values()), ('added but not in the table', sorted(new - set(decl.values()))[:20],
                                       'in the table but not added', sorted(set(decl.values()) - new)[:20])
    out['checked_against_receipts'] = [Path(sys.argv[1]).parent.name, Path(sys.argv[2]).parent.name]
# The rules text.py renames prose by, for tools that rename text without the R29 declaration list (the RO build):
# `text_windows`, a qualified suffix of at least two components every declaration ending in which is renamed to one
# form; `text_words`, a one-component name every declaration of which is renamed to one name, where it cannot be an
# English word or the retired label G0; `text_backticked`, such one-component names inside backticks.
sys.path.insert(0, str(HERE))
import text  # noqa: E402
out['text_windows'] = {'.'.join(w): '.'.join(n) for w, n in sorted(text.windows.items())}
out['text_words'] = {c: n for c, n in sorted(text.GLOBAL.items()) if text.identifier_like(c) and c not in text.LABELS}
out['text_backticked'] = dict(sorted(text.GLOBAL.items()))
json.dump(out, open(HERE / 'RENAME-TABLE.json', 'w'), indent=1, ensure_ascii=False)
print(len(decl), 'declarations,', len(mods), 'modules,', len(nss), 'namespaces;', len(nren), 'rows not renamed')
