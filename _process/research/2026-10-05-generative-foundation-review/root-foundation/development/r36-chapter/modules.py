"""R36: the Lean modules the argument cites, as one generated block of section 9.

The 20 October editions linked Lean files inline wherever a law was stated; the restructured chapter names
declarations and records instead. So that every module the frozen editions linked is still linked from the
live chapter (the Lean catalogue's "Theory" link follows inline links), this writes, between the markers
`<!-- modules:begin -->` and `<!-- modules:end -->` of section 9 (inserted before "**Names.**" on the first
run), every Lean file the two frozen editions link that still exists outside a history folder, core modules
first, then the periphery by directory. Without --apply, it prints the block.

Usage: python3 -B modules.py [--apply]
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[6]
CH = ROOT / 'theories/becoming/chapters'
LIVE = CH / 'THE-THEORY-OF-BECOMING.md'
FROZEN = [ROOT / 'theories/becoming/history/THE-THEORY-OF-BECOMING-2026-10-20.md',
          ROOT / 'theories/becoming/history/THE-THEORY-OF-BECOMING-2026-10-20.zh.md']
LINK = re.compile(r'\]\(([^)\s#]+\.lean)(?:#[^)\s]*)?\)')
BEGIN, END = '<!-- modules:begin -->', '<!-- modules:end -->'
CORE = 'experiments/integrated-correction/general-framework/generative-basis/lean/becoming/Becoming/'


def targets():
    out = set()
    for f in FROZEN:
        for t in LINK.findall(f.read_text()):
            # the frozen copies sit at the same depth as the chapters, so their relative links resolve alike
            p = (CH / t).resolve()
            try:
                rel = p.relative_to(ROOT.resolve()).as_posix()
            except ValueError:
                continue
            if p.is_file() and '/history/' not in '/' + rel:
                out.add(rel)
    return out


def block(paths):
    core = sorted(p for p in paths if p.startswith(CORE))
    rest = defaultdict(list)
    for p in sorted(set(paths) - set(core)):
        rest[str(Path(p).parent)].append(p)

    def link(p):
        name = p[len(CORE):-5].replace('/', '.') if p.startswith(CORE) else Path(p).stem
        prefix = 'Becoming.' if p.startswith(CORE) else ''
        return f'[{prefix}{name}](../../../{p})'

    lines = [BEGIN,
             f'**Modules the argument cites.** The {len(paths)} Lean files the 20 October editions linked inline, '
             'each still a working source (generated by the kit\'s `modules.py`; the laws themselves are named in '
             'the sections and the theorem map). '
             f'*Core* ({len(core)}): ' + ', '.join(link(p) for p in core) + '.']
    for d, ps in sorted(rest.items()):
        short = d.replace('experiments/integrated-correction/general-framework/generative-basis/', '')
        lines.append(f'*{short}* ({len(ps)}): ' + ', '.join(link(p) for p in ps) + '.')
    lines.append(END)
    return '\n\n'.join(lines)


def main():
    paths = targets()
    b = block(paths)
    text = LIVE.read_text()
    if BEGIN in text:
        new = text[:text.index(BEGIN)] + b + text[text.index(END) + len(END):]
    else:
        anchor = '\n**Names.** Declarations follow the naming criteria'
        assert text.count(anchor) == 1
        new = text.replace(anchor, '\n' + b + '\n' + anchor)
    if '--apply' in sys.argv:
        LIVE.write_text(new)
        print('applied', len(paths), 'files,', len(b), 'bytes')
    else:
        print(b[:3000])
        print(len(paths), 'files,', len(b), 'bytes')


if __name__ == '__main__':
    main()
