#!/usr/bin/env python3
"""R35 step 2(d), E4: record id renames with redirects. Adds `research.py rename-id` (tools/research/rename_ids.py),
the optional record field `former_ids` (checked: ids, unique, never a live id), a generated redirect page at each
former id's page, search over former ids, and text versions whose earlier id is a former id.
Run once from the checkout root: python3 -B tools_e4.py"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[6]


def patch(path, pairs):
    p = ROOT / path
    s = p.read_text()
    for a, b in pairs:
        assert s.count(a) == 1, (path, a[:80])
        s = s.replace(a, b)
    p.write_text(s)


