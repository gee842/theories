"""Check only this philosophical round's new material and recorded insertions."""
from pathlib import Path
import hashlib
import json
import re
from urllib.parse import unquote, urlsplit

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
LEDGER = HERE / "MINIMUM-GROUNDING-CONTINUATION-EDITS.json"
OUTPUT = HERE / "MINIMUM-GROUNDING-CONTINUATION-CHECKS.json"


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def anchors(path):
    found, counts = set(), {}
    for line in path.read_text().splitlines():
        match = re.match(r"^#{1,6}\s+(.+?)\s*#*\s*$", line)
        if not match:
            continue
        title = re.sub(r"\[([^]]+)\]\([^)]*\)", r"\1", match[1]).lower()
        slug = re.sub(r"[^\w\- ]", "", title).replace(" ", "-")
        index = counts.get(slug, 0)
        counts[slug] = index + 1
        found.add(slug if index == 0 else f"{slug}-{index}")
    return found


edits = json.loads(LEDGER.read_text())["edits"]
new_files = [HERE / name for name in (
    "DIRECT-GROUNDING-EPISTEMOLOGY.md",
    "PATIENT-GROUND-AFTER-FAIR-ALLOCATION.md",
    "PATIENT-GROUND-AND-AGENT-SCOPE-SOURCES.md",
    "MINIMUM-GROUNDING-CONTINUATION.md",
)] + [ROOT / "sources/37-ethical-minimum-primary-2026-10-06/README.md"]
errors, links = [], []
scopes = [(path, path.read_text()) for path in new_files]
scopes += [(ROOT / edit["file"], edit["new"]) for edit in edits]
for source, body in scopes:
    for target in re.findall(r"\]\(([^)]+)\)", body):
        parsed = urlsplit(target.strip("<>"))
        if parsed.scheme or parsed.netloc:
            continue
        path = (source.parent / unquote(parsed.path)).resolve() if parsed.path else source
        # The receipt is generated by this check, and is intentionally linked beforehand.
        exists = path.exists() or path == OUTPUT
        fragment = unquote(parsed.fragment)
        valid_anchor = not fragment or (exists and path.suffix == ".md" and fragment in anchors(path))
        passed = exists and valid_anchor
        links.append({"source":str(source.relative_to(ROOT)),"target":target,"passed":passed})
        if not passed:
            errors.append(f"Link: {source.relative_to(ROOT)} -> {target}")
    for line in body.splitlines():
        if line != line.rstrip():
            errors.append(f"Trailing whitespace in scoped text: {source.relative_to(ROOT)}")

# Reverse exact insertions on in-memory copies, preserving other sessions' edits.
copies = {edit["file"]:(ROOT / edit["file"]).read_text() for edit in edits}
for edit in reversed(edits):
    content = copies[edit["file"]]
    if content.count(edit["new"]) == 1:
        copies[edit["file"]] = content.replace(edit["new"], edit["old"], 1)
    elif edit["new"].startswith(edit["old"]) and edit["new"] != edit["old"]:
        # Concurrent index additions can now stand between the heading and ours.
        addition = edit["new"][len(edit["old"]):]
        if content.count(addition) == 1 and edit["old"] in content:
            copies[edit["file"]] = content.replace(addition, "", 1)
        else:
            errors.append(f"Scoped insertion not uniquely recoverable: {edit['file']}")
    else:
        errors.append(f"Scoped insertion not uniquely recoverable: {edit['file']}")

preservation = json.loads((HERE / "development/MINIMUM-GROUNDING-BEFORE.json").read_text())["files"]
hashes = []
for item in preservation:
    actual = digest(ROOT / item["snapshot"])
    passed = actual == item["sha256"]
    hashes.append({"file":item["snapshot"],"sha256":actual,"passed":passed})
    if not passed:
        errors.append(f"Preservation hash: {item['snapshot']}")
pdf = ROOT / "sources/37-ethical-minimum-primary-2026-10-06/mcmahan-2021-suffering-and-moral-status-author-hosted.pdf"
pdf_hash = digest(pdf)
pdf_passed = pdf_hash == "12a05b6373369b04159e787db0af78ccaedf98eedb670e443a83608db9ab37eb" and pdf.stat().st_size == 268501
hashes.append({"file":str(pdf.relative_to(ROOT)),"sha256":pdf_hash,"bytes":pdf.stat().st_size,"passed":pdf_passed})
if not pdf_passed:
    errors.append("Preserved primary PDF hash or size mismatch")

record = {
    "scope":"New philosophical notes, source README, exact recorded insertions and preserved bytes; no scientific or Lean verification in this round.",
    "passed":not errors,
    "links":links,
    "preservation":hashes,
    "scoped_edits_recoverable":not any("recoverable" in error for error in errors),
    "current_files":[{"file":str(path.relative_to(ROOT)),"sha256":digest(path)} for path in sorted(set(new_files + [ROOT / edit["file"] for edit in edits]))],
    "internal_review":{
        "scope":"Internal AI argument and source checks, not external peer review or validation of ethical truth.",
        "reciprocal_note_review":"Passed with the fair-draw permission/exclusion clarification incorporated.",
        "final_source_and_canonical_review":"Passed; clarified that the allocation comparison preserves the possibility of genuine exclusion, rather than establishing it.",
        "parent_primary_check":"Central epistemic qualifications and McMahan causing-versus-relieving scope checked."
    },
    "errors":errors,
}
OUTPUT.write_text(json.dumps(record,ensure_ascii=False,indent=2)+"\n")
print(json.dumps({"passed":not errors,"links_checked":len(links),"preservation_hashes":len(hashes),"errors":errors},ensure_ascii=False))
raise SystemExit(bool(errors))
